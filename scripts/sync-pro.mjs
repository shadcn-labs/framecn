#!/usr/bin/env node
/**
 * Syncs framecn Pro component sources from the private shadcn-labs/framecn-pro
 * repository into the gitignored `registry/pro/` so the gallery and detail
 * panels can render live Pro previews. Pro source is never committed here.
 *
 *   node scripts/sync-pro.mjs              sync sources + generate registry/pro/__index__.tsx
 *   node scripts/sync-pro.mjs --catalog    also regenerate the committed lib/pro-catalog.ts
 *   node scripts/sync-pro.mjs --if-missing only write the stub index when nothing is synced yet
 *   node scripts/sync-pro.mjs --no-env-file  ignore .env.local (FRAMECN_PRO_SKIP_ENV_FILE=1 works too)
 *
 * Without FRAMECN_PRO_GITHUB_TOKEN (e.g. forks) it writes a stub index that
 * exports no entries and exits 0; Pro cards then show a locked placeholder.
 */
import { existsSync } from "node:fs";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, posix, relative } from "node:path";
import { gunzipSync } from "node:zlib";

const REPO = "shadcn-labs/framecn-pro";
const BRANCH = "main";
const SOURCE_PREFIX = "registry/bases/editframe/";
const PUBLIC_ALIAS = "@/registry/bases/editframe/";
const PRO_ALIAS = "@/registry/pro/";

const root = join(import.meta.dirname, "..");
const proDir = join(root, "registry", "pro");
const indexFile = join(proDir, "__index__.tsx");
const publicLibDir = join(root, "registry", "bases", "editframe", "lib");
const catalogFile = join(root, "lib", "pro-catalog.ts");

const args = new Set(process.argv.slice(2));
const writeCatalog = args.has("--catalog");

/** framecn-pro group directory → this site's catalog category. */
const CATEGORY_BY_GROUP = {
  "3d-sphere": "globes",
  carousels: "carousels",
  charts: "charts",
  collage: "collages",
  components: "compositions",
  creative: "compositions",
  "full-composition": "compositions",
  "scroll-animations": "scroll-animations",
  text: "text",
};

const log = (message) => console.log(`[sync-pro] ${message}`);

const HEADER = (detail) =>
  `// Generated by scripts/sync-pro.mjs (${detail}). Do not edit.\n`;

const STUB_INDEX = `${HEADER("Pro sources not synced")}import type { RegistryEntry } from "@/lib/registry-types";

const registry: Record<string, RegistryEntry> = {};

export default registry;
`;

const writeStub = async () => {
  await rm(proDir, { force: true, recursive: true });
  await mkdir(proDir, { recursive: true });
  await writeFile(indexFile, STUB_INDEX);
};

/** Minimal ustar/pax reader: enough for GitHub's `git archive` tarballs. */
const readTar = (buffer) => {
  const files = new Map();
  let offset = 0;
  let paxPath;
  while (offset + 512 <= buffer.length) {
    const header = buffer.subarray(offset, offset + 512);
    if (header.every((byte) => byte === 0)) {
      break;
    }
    const field = (start, length) =>
      header
        .subarray(start, start + length)
        .toString("utf-8")
        .split("\0")[0];
    const size = Number.parseInt(field(124, 12).trim() || "0", 8);
    const type = field(156, 1);
    const prefix = field(345, 155);
    const name = prefix ? `${prefix}/${field(0, 100)}` : field(0, 100);
    const body = buffer.subarray(offset + 512, offset + 512 + size);
    offset += 512 + Math.ceil(size / 512) * 512;

    if (type === "x") {
      const match = body.toString("utf-8").match(/^\d+ path=(.*)$/m);
      paxPath = match?.[1];
      continue;
    }
    if (type === "g") {
      continue;
    }
    const path = paxPath ?? name;
    paxPath = undefined;
    if (type === "0" || type === "") {
      files.set(path, body);
    }
  }
  return files;
};

const download = async (token) => {
  const response = await fetch(
    `https://api.github.com/repos/${REPO}/tarball/${BRANCH}`,
    {
      headers: {
        Accept: "application/vnd.github+json",
        Authorization: `Bearer ${token}`,
        "X-GitHub-Api-Version": "2022-11-28",
      },
    }
  );
  if (!response.ok) {
    throw new Error(
      `GitHub responded ${response.status} for ${REPO}@${BRANCH}`
    );
  }
  const archive = readTar(
    gunzipSync(Buffer.from(await response.arrayBuffer()))
  );
  // Every entry sits under a single `<owner>-<repo>-<sha>/` directory.
  const files = new Map();
  let sha = "";
  for (const [path, body] of archive) {
    const slash = path.indexOf("/");
    sha ||= path.slice(0, slash).split("-").pop() ?? "";
    files.set(path.slice(slash + 1), body);
  }
  return { files, sha: sha.slice(0, 12) };
};

/** Shared runtime modules whose React context must be the one the preview provides. */
const publicLibModules = async () =>
  new Set(existsSync(publicLibDir) ? await readdir(publicLibDir) : []);

const toProSource = (content) => content.replaceAll(PUBLIC_ALIAS, PRO_ALIAS);

const extract = async (files) => {
  const shared = await publicLibModules();
  await rm(proDir, { force: true, recursive: true });
  let count = 0;
  for (const [path, body] of files) {
    if (!path.startsWith(SOURCE_PREFIX)) {
      continue;
    }
    const relativePath = path.slice(SOURCE_PREFIX.length);
    const target = join(proDir, ...relativePath.split("/"));
    await mkdir(dirname(target), { recursive: true });
    const moduleName = relativePath.replace(/^lib\//, "");
    let content = body;
    if (relativePath.startsWith("lib/") && shared.has(moduleName)) {
      // Re-export this repo's copy so Pro components read the same
      // FrameContext the preview's FrameProvider sets.
      const publicContent = await readFile(join(publicLibDir, moduleName));
      if (!publicContent.equals(body)) {
        log(
          `warning: framecn-pro lib/${moduleName} differs from this repo's copy; using this repo's.`
        );
      }
      const specifier = `${PUBLIC_ALIAS}lib/${moduleName.replace(/\.tsx?$/, "")}`;
      content = Buffer.from(`export * from "${specifier}";\n`);
    } else if (/\.(?:[cm]?[jt]sx?)$/.test(path)) {
      content = Buffer.from(toProSource(body.toString("utf-8")));
    }
    await writeFile(target, content);
    count += 1;
  }
  return count;
};

/** Export names per item, read from framecn-pro's own registry/__index__.tsx. */
const parseProIndex = (source) => {
  const configs = new Map();
  for (const [, configName, path] of source.matchAll(
    /import \{ (\w+) \} from "@\/registry\/bases\/editframe\/([^"]+)\/config";/g
  )) {
    configs.set(path, configName);
  }
  const entries = new Map();
  for (const [, name, componentName, path, configName] of source.matchAll(
    /"?([\w-]+)"?:\s*\{\s*Component:\s*lazy\(async \(\) => \{\s*const \{ (\w+) \}\s*=\s*await import\("@\/registry\/bases\/editframe\/([^"]+)"\);[\s\S]*?\}\),\s*config:\s*(\w+),/g
  )) {
    if (configs.get(path) === configName) {
      entries.set(name, { componentName, configName, path });
    }
  }
  return entries;
};

const loadProCatalog = async () => {
  if (!existsSync(catalogFile)) {
    return [];
  }
  const { createJiti } = await import("jiti");
  const jiti = createJiti(import.meta.url);
  const { PRO_CATALOG } = await jiti.import(catalogFile);
  return PRO_CATALOG;
};

/** Free catalog ids (Pro ids that collide are skipped) and the category order. */
const loadCatalog = async (proCatalog) => {
  const { createJiti } = await import("jiti");
  const jiti = createJiti(import.meta.url, { alias: { "@": root } });
  const { CATALOG, COMPONENT_CATEGORIES } = await jiti.import(
    join(root, "lib", "catalog.ts")
  );
  const synced = new Set(proCatalog.map((item) => item.id));
  return {
    categories: COMPONENT_CATEGORIES,
    freeIds: new Set(
      CATALOG.filter((item) => !synced.has(item.id)).map((item) => item.id)
    ),
  };
};

const componentItems = (manifest) =>
  manifest.items.filter((item) => item.type === "registry:component");

/** framecn-pro group directory of a registry item, e.g. `carousels`. */
const groupOf = (item) =>
  item.files[0].path.slice(SOURCE_PREFIX.length).split("/")[0];

const generateCatalog = async (manifest) => {
  const { categories, freeIds } = await loadCatalog(await loadProCatalog());
  const skipped = [];
  const items = [];
  for (const item of componentItems(manifest)) {
    if (freeIds.has(item.name)) {
      skipped.push(item.name);
      continue;
    }
    const category = CATEGORY_BY_GROUP[groupOf(item)];
    if (!category) {
      throw new Error(
        `No catalog category for ${item.name} (${groupOf(item)})`
      );
    }
    items.push({
      category,
      description: (item.description ?? "").trim(),
      id: item.name,
      name: (item.title ?? item.name).trim(),
      pro: true,
    });
  }
  items.sort(
    (a, b) => categories.indexOf(a.category) - categories.indexOf(b.category)
  );
  const body = items
    .map(
      (item) => `  {
    category: ${JSON.stringify(item.category)},
    description:
      ${JSON.stringify(item.description)},
    id: ${JSON.stringify(item.id)},
    name: ${JSON.stringify(item.name)},
    pro: true,
  },`
    )
    .join("\n");
  await writeFile(
    catalogFile,
    `// Generated by \`node scripts/sync-pro.mjs --catalog\` from framecn-pro's registry.json.
// Metadata only: Pro sources are synced into the gitignored registry/pro/.
import type { CatalogItem } from "@/lib/catalog";

export const PRO_CATALOG: CatalogItem[] = [
${body}
];
`
  );
  log(
    `wrote lib/pro-catalog.ts (${items.length} items; skipped ${skipped.join(", ") || "none"} — already in CATALOG)`
  );
  return items;
};

const generateIndex = async (manifest, proIndexSource, proCatalog, sha) => {
  const exportsByName = parseProIndex(proIndexSource);
  const manifestByName = new Map(
    componentItems(manifest).map((item) => [item.name, item])
  );
  const imports = [];
  const entries = [];
  for (const { id } of [...proCatalog].toSorted((a, b) =>
    a.id.localeCompare(b.id)
  )) {
    const item = manifestByName.get(id);
    const names = exportsByName.get(id);
    if (!(item && names)) {
      log(`warning: ${id} is missing from framecn-pro; its card stays locked.`);
      continue;
    }
    const dir = posix.dirname(item.files[0].path).slice(SOURCE_PREFIX.length);
    if (dir !== names.path || !existsSync(join(proDir, dir, "config.ts"))) {
      log(`warning: ${id} has no config at registry/pro/${dir}; skipped.`);
      continue;
    }
    imports.push(
      `import { ${names.configName} } from "${PRO_ALIAS}${dir}/config";`
    );
    entries.push(`  ${JSON.stringify(id)}: {
    Component: lazy(async () => {
      const { ${names.componentName} } = await import("${PRO_ALIAS}${dir}");
      return { default: ${names.componentName} };
    }),
    config: ${names.configName},
  },`);
  }
  await writeFile(
    indexFile,
    `${HEADER(`${REPO}@${sha}`)}"use client";

import dynamic from "next/dynamic";

import type { RegistryComponent, RegistryEntry } from "@/lib/registry-types";
${imports.join("\n")}

const lazy = (loader: () => Promise<{ default: RegistryComponent }>) =>
  dynamic(loader, { ssr: false });

const registry: Record<string, RegistryEntry> = {
${entries.join("\n")}
};

export default registry;
`
  );
  return entries.length;
};

const main = async () => {
  if (args.has("--if-missing") && existsSync(indexFile)) {
    return;
  }
  if (
    !(args.has("--no-env-file") || process.env.FRAMECN_PRO_SKIP_ENV_FILE) &&
    existsSync(join(root, ".env.local"))
  ) {
    process.loadEnvFile(join(root, ".env.local"));
  }
  const token = process.env.FRAMECN_PRO_GITHUB_TOKEN;
  if (!token || args.has("--if-missing")) {
    if (writeCatalog) {
      throw new Error("--catalog needs FRAMECN_PRO_GITHUB_TOKEN.");
    }
    await writeStub();
    log(
      token
        ? "wrote a stub registry/pro/__index__.tsx."
        : "FRAMECN_PRO_GITHUB_TOKEN is not set; Pro previews are disabled (stub index written)."
    );
    return;
  }

  let archive;
  try {
    archive = await download(token);
  } catch (error) {
    if (existsSync(indexFile) && !writeCatalog) {
      log(
        `warning: could not download ${REPO} (${error.message}); keeping the existing registry/pro/.`
      );
      return;
    }
    throw error;
  }
  const { files, sha } = archive;
  const manifestFile = files.get("registry.json");
  const proIndexFile = files.get("registry/__index__.tsx");
  if (!(manifestFile && proIndexFile)) {
    throw new Error(`${REPO} has no registry.json or registry/__index__.tsx`);
  }
  const manifest = JSON.parse(manifestFile.toString("utf-8"));

  const count = await extract(files);
  const proCatalog = writeCatalog
    ? await generateCatalog(manifest)
    : await loadProCatalog();
  const entries = await generateIndex(
    manifest,
    proIndexFile.toString("utf-8"),
    proCatalog,
    sha
  );
  log(
    `synced ${count} files from ${REPO}@${sha} into ${relative(root, proDir)}/ (${entries} preview entries).`
  );
};

try {
  await main();
} catch (error) {
  console.error(`[sync-pro] ${error.message}`);
  process.exit(1);
}
